// Utility function to get all images with optimized shuffling for better masonry layout
export const getAllImages = () => {
  const allImages = [
    ...galleryData.featured,
    ...galleryData.events,
    ...galleryData.workshops,
    ...galleryData.competitions
  ];
  
  // Shuffle algorithm for better visual distribution in masonry
  const shuffled = [];
  const categories = {
    featured: [...galleryData.featured],
    events: [...galleryData.events],
    workshops: [...galleryData.workshops],
    competitions: [...galleryData.competitions]
  };
  
  // Interleave images from different categories for better visual balance
  const categoryKeys = Object.keys(categories);
  let categoryIndex = 0;
  
  while (shuffled.length < allImages.length) {
    const currentCategory = categoryKeys[categoryIndex];
    if (categories[currentCategory].length > 0) {
      shuffled.push(categories[currentCategory].shift());
    }
    categoryIndex = (categoryIndex + 1) % categoryKeys.length;
  }
  
  return shuffled;
};

// Utility function to get images by category
export const getImagesByCategory = (category) => {
  if (category === 'all') return getAllImages();
  return galleryData[category] || [];
};
